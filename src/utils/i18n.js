export function translate(locale, key, values = {}) {
  const template = MESSAGES[locale]?.[key] ?? (locale === 'en-US' ? ENGLISH_TEXT[key] : undefined) ?? MESSAGES['pt-BR'][key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`)
}

export function translateText(locale, text) {
  const trimmed = text.trim()
  if (!trimmed) return text
  const start = text.slice(0, text.length - text.trimStart().length)
  const end = text.slice(text.trimEnd().length)
  return `${start}${translate(locale, trimmed)}${end}`
}

export function hasTranslation(locale, text) {
  const key = text.trim()
  return locale === 'pt-BR' || MESSAGES[locale]?.[key] !== undefined || (locale === 'en-US' && ENGLISH_TEXT[key] !== undefined)
}

export function translateActiveText(text) {
  return translateText(getActiveLocale(), text)
}
